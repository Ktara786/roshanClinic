/**
 * Same nested shape as `en`, but every leaf is widened to `string` so other
 * locales can provide different literal text while TypeScript still
 * enforces that every key exists.
 */
type DeepStringify<T> = T extends string
  ? string
  : { [K in keyof T]: DeepStringify<T[K]> };

export type Translations = DeepStringify<typeof en>;
